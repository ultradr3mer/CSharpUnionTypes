using UnionTypes;
using BasicSample;

string | int value = 42;

var example = new Example { Value = "hello" };
Console.WriteLine(example.Describe());

var result = value.Match(s => $"s:{s}", i => $"i:{i}");
Console.WriteLine(result);

var nonZeroEnumerable = ExampleFunction.NonZeroEnumerable(new int[] { -1, 0, 1, 2, 3 });
Console.WriteLine($"ExampleFunction.NonZeroEnumerable(new int[] {{ -1, 0, 1, 2, 3 }}): {string.Join(", ", nonZeroEnumerable)}");

var nonZeroInt1 = ExampleFunction.NonZeroEnumerable(1);
Console.WriteLine($"ExampleFunction.NonZeroEnumerable(1): {string.Join(", ", nonZeroInt1)}");

// 3-variant union
string | int | bool multi = "test";
Console.WriteLine($"Describe3(\"test\"): {ExampleFunction.Describe3(multi)}");
multi = 42;
Console.WriteLine($"Describe3(42): {ExampleFunction.Describe3(multi)}");
multi = true;
Console.WriteLine($"Describe3(true): {ExampleFunction.Describe3(multi)}");

// 4-variant union
string | int | bool | double multi4 = 3.14;
Console.WriteLine($"Describe4(3.14): {ExampleFunction.Describe4(multi4)}");

// Pattern matching via Deconstruct (generated by source generator)
var (s, i) = value;
Console.WriteLine($"Deconstruct value: s={s}, i={i}");

var (s3, i3, b3) = multi;
Console.WriteLine($"Deconstruct multi: s3={s3}, i3={i3}, b3={b3}");