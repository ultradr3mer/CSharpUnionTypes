using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace UnionTypes.Generators;

/// <summary>
/// Source generator that generates <c>Deconstruct</c> extension methods for
/// every <c>Union&lt;T1, ...&gt;</c> instantiation found in the compilation.
/// This enables positional deconstruction and C# pattern matching:
/// <code>
/// Union&lt;string, int&gt; u = "hello";
/// var (s, i) = u;
/// </code>
/// </summary>
[Generator]
public sealed class UnionDeconstructGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var usages = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: IsPotentialUnionGeneric,
                transform: ExtractUnionType)
            .Where(x => x is not null)
            .Collect();

        context.RegisterSourceOutput(usages, GenerateSource);
    }

    private static bool IsPotentialUnionGeneric(SyntaxNode node, CancellationToken _)
    {
        if (node is not GenericNameSyntax g) return false;
        return g.Identifier.Text == "Union"
            && g.TypeArgumentList.Arguments.Count >= 2
            && g.TypeArgumentList.Arguments.Count <= 4;
    }

    private static UnionUsage? ExtractUnionType(GeneratorSyntaxContext context, CancellationToken _)
    {
        var g = (GenericNameSyntax)context.Node;
        var args = g.TypeArgumentList.Arguments;

        // Skip unbound generic names like Union<,> (used in typeof() expressions).
        if (args.Any(a => a is OmittedTypeArgumentSyntax))
            return null;

        var symbol = context.SemanticModel.GetSymbolInfo(g).Symbol as INamedTypeSymbol;
        if (symbol is null) return null;

        if (symbol.Name != "Union" || symbol.ContainingNamespace?.Name != "UnionTypes")
            return null;

        if (symbol.TypeParameters.Length < 2 || symbol.TypeParameters.Length > 4)
            return null;

        var typeArgs = args.Select(a => a.ToString()).ToImmutableArray();
        var key = $"Union_{string.Join("_", typeArgs)}";

        return new UnionUsage(key, typeArgs);
    }

    private static void GenerateSource(
        SourceProductionContext context,
        ImmutableArray<UnionUsage?> usages)
    {
        var seen = new HashSet<string>();
        var distinct = new List<UnionUsage>();
        foreach (var u in usages)
        {
            if (u is { } usage && seen.Add(usage.Key))
            {
                distinct.Add(usage);
            }
        }

        if (distinct.Count == 0) return;

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("// Union Deconstruct extension methods generated by UnionTypes.Generators");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace UnionTypes");
        sb.AppendLine("{");
        sb.AppendLine("    public static class UnionDeconstructExtensions");
        sb.AppendLine("    {");

        bool first = true;
        foreach (var usage in distinct)
        {
            if (!first) sb.AppendLine();
            first = false;
            GenerateDeconstruct(sb, usage);
        }

        sb.AppendLine("    }");
        sb.AppendLine("}");

        context.AddSource("UnionDeconstructExtensions.g.cs", sb.ToString());
    }

    private static void GenerateDeconstruct(StringBuilder sb, UnionUsage usage)
    {
        var args = usage.TypeArgs;
        int n = args.Length;

        sb.Append("        public static void Deconstruct(this global::UnionTypes.Union");
        sb.Append($"<{string.Join(", ", args)}>");
        sb.Append(" u");

        for (int i = 0; i < n; i++)
        {
            sb.Append($", out {args[i]}? t{i + 1}");
        }

        sb.AppendLine(")");
        sb.AppendLine("        {");
        for (int i = 0; i < n; i++)
        {
            sb.AppendLine($"            u.TryGetT{i + 1}(out var v{i + 1});");
            sb.AppendLine($"            t{i + 1} = v{i + 1};");
        }
        sb.AppendLine("        }");
    }

    private sealed class UnionUsage
    {
        public string Key { get; }
        public ImmutableArray<string> TypeArgs { get; }

        public UnionUsage(string key, ImmutableArray<string> typeArgs)
        {
            Key = key;
            TypeArgs = typeArgs;
        }
    }
}